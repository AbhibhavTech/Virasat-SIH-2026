// Helper to write curated festivals
export function writeCuratedDatasets(baseDir = '.') {
  console.log(`Writing ${USER_CURATED_FESTIVALS.length} curated festivals to ${baseDir}...`);
  
  // 1. virasat_store.json
  const storePath = path.join(baseDir, 'data/.database/virasat_store.json');
  if (fs.existsSync(storePath)) {
    const store = JSON.parse(fs.readFileSync(storePath, 'utf8'));
    const newFestivalsMap = {};
    for (const fest of USER_CURATED_FESTIVALS) {
      newFestivalsMap[fest.id] = fest;
    }
    store.festivals = newFestivalsMap;
    fs.writeFileSync(storePath, JSON.stringify(store, null, 2), 'utf8');
    console.log(`Updated ${storePath} with ${Object.keys(newFestivalsMap).length} festivals.`);
  }

  // 2. festivals.json
  const festPath = path.join(baseDir, 'data/festivals.json');
  fs.writeFileSync(festPath, JSON.stringify(USER_CURATED_FESTIVALS, null, 2), 'utf8');
  console.log(`Updated ${festPath} with ${USER_CURATED_FESTIVALS.length} festivals.`);

  // 3. festivals_master.json
  const masterPath = path.join(baseDir, 'data/festivals_master.json');
  fs.writeFileSync(masterPath, JSON.stringify(USER_CURATED_FESTIVALS, null, 2), 'utf8');
  console.log(`Updated ${masterPath} with ${USER_CURATED_FESTIVALS.length} festivals.`);

  // 4. verified_festivals_reference.json
  const refPath = path.join(baseDir, 'data/verified_festivals_reference.json');
  fs.writeFileSync(refPath, JSON.stringify(USER_CURATED_FESTIVALS, null, 2), 'utf8');
  console.log(`Updated ${refPath} with ${USER_CURATED_FESTIVALS.length} festivals.`);
}

if (process.argv[1] && process.argv[1].endsWith('curate_user_festivals.mjs')) {
  writeCuratedDatasets('.');
}
