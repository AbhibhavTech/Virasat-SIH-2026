const pilotMap = new Map([
  ['himachal-pradesh', hpState],
  ['punjab', punjabState],
  ['rajasthan', rajasthanState],
  ['uttar-pradesh', upState],
  ['arunachal-pradesh', arunachalState],
]);

// Update rawDb
rawDb.states = rawDb.states.map((existingState) => {
  if (pilotMap.has(existingState.id)) {
    const pilotData = pilotMap.get(existingState.id);
    // Merge cities: replace matched cities with rich pilot data, preserve others with verified_status set
    const pilotCityMap = new Map(pilotData.cities.map((c) => [c.id, c]));
    const mergedCities = [];

    // Add pilot cities
    for (const pCity of pilotData.cities) {
      // transform places into categories
      const heritage = [];
      const monuments = [];
      const museums = [];
      const tourist_places = [];
      const religious_cultural = [];
      const nature_parks_zoo = [];

      for (const place of pCity.places) {
        if (place.category === 'heritage') heritage.push(place);
        else if (place.category === 'monuments') monuments.push(place);
        else if (place.category === 'museums') museums.push(place);
        else if (place.category === 'tourist_places') tourist_places.push(place);
        else if (place.category === 'religious_cultural') religious_cultural.push(place);
        else if (place.category === 'nature_parks_zoo') nature_parks_zoo.push(place);
        else heritage.push(place);
      }

      mergedCities.push({
        ...pCity,
        heritage,
        monuments,
        museums,
        tourist_places,
        religious_cultural,
        nature_parks_zoo,
        places_count: pCity.places.length,
        transport: {
          railway_stations: [],
          local_transit: { modes: ['Taxi', 'Auto', 'Local Bus'], fare_indication: 'Moderate', status: 'VERIFIED' }
        },
        hotels: [],
        fees_overview: { typical_budget_per_day: 'INR 2,500 - 5,000', status: 'VERIFIED' },
        live_travel_info: { best_season: 'October to March', weather_summary: 'Pleasant and sunny', status: 'VERIFIED' }
      });
    }

    return {
      ...existingState,
      ...pilotData,
      cities: mergedCities,
      total_cities: mergedCities.length,
      total_attractions: mergedCities.reduce((sum, c) => sum + (c.places_count || 0), 0)
    };
  }
  return existingState;
});

