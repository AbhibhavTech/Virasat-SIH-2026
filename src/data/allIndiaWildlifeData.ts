// Lookup helpers
export function getWildlifeReservesByState(stateKey: string): WildlifeReserveEntity[] {
  if (!stateKey) return [];
  const normalized = stateKey.trim().toLowerCase().replace(/\s+/g, '-');
  return ALL_INDIA_WILDLIFE_RESERVES.filter(
    (r) =>
      r.stateId === normalized ||
      r.stateName.toLowerCase() === stateKey.toLowerCase() ||
      normalized.includes(r.stateId) ||
      r.stateId.includes(normalized)
  );
}

export function getAllWildlifeReserves(): WildlifeReserveEntity[] {
  return ALL_INDIA_WILDLIFE_RESERVES;
}

export function getWildlifeStats() {
  const tigerReserves = ALL_INDIA_WILDLIFE_RESERVES.filter((r) => r.category === 'Tiger Reserve').length;
  const nationalParks = ALL_INDIA_WILDLIFE_RESERVES.filter((r) => r.category === 'National Park' || r.category === 'Marine National Park').length;
  const unescoReserves = ALL_INDIA_WILDLIFE_RESERVES.filter((r) => r.isUnesco).length;
  const total = ALL_INDIA_WILDLIFE_RESERVES.length;

  return {
    total,
    tigerReserves,
    nationalParks,
    unescoReserves,
  };
}
