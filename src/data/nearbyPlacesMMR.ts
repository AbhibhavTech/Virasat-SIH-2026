/**
 * Helper to compute Haversine distance in kilometers between two geo-coordinates
 */
export function calculateHaversineKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

/**
 * Filter nearby places around given lat/lng within a radius, with dynamic distance calculation
 */
export function getNearbyDiscoveryPlaces(
  lat: number,
  lng: number,
  radiusKm = 50,
  categoryFilter = 'all'
): NearbyDiscoveryItem[] {
  return NEARBY_DISCOVERY_DATABASE.map((item) => {
    const dist = calculateHaversineKm(lat, lng, item.lat, item.lng);
    return { ...item, distance_km: dist };
  })
    .filter((item) => {
      const withinRadius = (item.distance_km ?? 9999) <= radiusKm;
      if (!withinRadius) return false;
      if (categoryFilter === 'all') return true;
      return item.category === categoryFilter;
    })
    .sort((a, b) => (a.distance_km ?? 9999) - (b.distance_km ?? 9999));
}

