/**
 * Returns a verified real image for any monument, with graceful fallback.
 */
export function getRealMonumentImage(siteId?: string, siteName?: string): string {
  if (siteId && REAL_MONUMENT_IMAGES[siteId]) {
    return REAL_MONUMENT_IMAGES[siteId];
  }
  // Try normalized search
  if (siteId) {
    const norm = siteId.toLowerCase().trim();
    for (const [key, url] of Object.entries(REAL_MONUMENT_IMAGES)) {
      if (norm.includes(key) || key.includes(norm)) {
        return url;
      }
    }
  }
  if (siteName) {
    const normName = siteName.toLowerCase();
    if (normName.includes('taj mahal')) return REAL_MONUMENT_IMAGES['taj-mahal'];
    if (normName.includes('qutub')) return REAL_MONUMENT_IMAGES['qutub-minar'];
    if (normName.includes('red fort')) return REAL_MONUMENT_IMAGES['red-fort'];
    if (normName.includes('humayun')) return REAL_MONUMENT_IMAGES['humayuns-tomb'];
    if (normName.includes('india gate')) return REAL_MONUMENT_IMAGES['india-gate'];
    if (normName.includes('golden temple') || normName.includes('harmandir')) return REAL_MONUMENT_IMAGES['golden-temple-amritsar'];
    if (normName.includes('hawa mahal')) return REAL_MONUMENT_IMAGES['hawa-mahal'];
    if (normName.includes('amber')) return REAL_MONUMENT_IMAGES['amber-fort'];
    if (normName.includes('jaisalmer')) return REAL_MONUMENT_IMAGES['jaisalmer-fort'];
    if (normName.includes('ellora') || normName.includes('kailasa')) return REAL_MONUMENT_IMAGES['ellora-caves'];
    if (normName.includes('ajanta')) return REAL_MONUMENT_IMAGES['ajanta-caves'];
    if (normName.includes('gateway of india')) return REAL_MONUMENT_IMAGES['gateway-of-india'];
    if (normName.includes('csmt') || normName.includes('terminus')) return REAL_MONUMENT_IMAGES['csmt'];
    if (normName.includes('hampi')) return REAL_MONUMENT_IMAGES['hampi-monuments'];
    if (normName.includes('brihadisvara') || normName.includes('thanjavur')) return REAL_MONUMENT_IMAGES['brihadisvara-temple'];
    if (normName.includes('meenakshi')) return REAL_MONUMENT_IMAGES['meenakshi-amman-temple'];
    if (normName.includes('charminar')) return REAL_MONUMENT_IMAGES['charminar'];
    if (normName.includes('konark') || normName.includes('sun temple')) return REAL_MONUMENT_IMAGES['sun-temple-konark'];
    if (normName.includes('victoria')) return REAL_MONUMENT_IMAGES['victoria-memorial-kolkata'];
    if (normName.includes('mahabodhi')) return REAL_MONUMENT_IMAGES['mahabodhi-temple'];
    if (normName.includes('nalanda')) return REAL_MONUMENT_IMAGES['nalanda-university-ruins'];
    if (normName.includes('puducherry') || normName.includes('white town')) return REAL_MONUMENT_IMAGES['french-quarter-puducherry'];
    if (normName.includes('chandigarh') || normName.includes('capitol')) return REAL_MONUMENT_IMAGES['capitol-complex-chandigarh'];
    if (normName.includes('leh') || normName.includes('ladakh')) return REAL_MONUMENT_IMAGES['leh-palace'];
  }
  return 'https://images.unsplash.com/photo-1564507592333-c60657eea523?w=1200&auto=format&fit=crop&q=85';
}
