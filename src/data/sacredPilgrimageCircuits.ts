// CONVENIENCE ACCESSOR FUNCTIONS
// ==========================================

/**
 * Returns all 8 sacred pilgrimage circuits.
 */
export function getAllSacredCircuits(): SacredPilgrimageCircuit[] {
  return SACRED_PILGRIMAGE_CIRCUITS;
}

/**
 * Find circuit by unique ID.
 */
export function getSacredCircuitById(circuitId: string): SacredPilgrimageCircuit | undefined {
  return SACRED_PILGRIMAGE_CIRCUITS.find((c) => c.id === circuitId);
}

/**
 * Flattens and returns all 46 sacred sites.
 */
export function getAllSacredSites(): SacredSite[] {
  return SACRED_PILGRIMAGE_CIRCUITS.flatMap((c) => c.sites);
}

/**
 * Filter sacred sites by spiritual tradition.
 */
export function getSacredSitesByTradition(tradition: SacredSite['tradition']): SacredSite[] {
  return getAllSacredSites().filter((site) => site.tradition === tradition);
}

/**
 * Filter sacred sites by city name (case-insensitive substring match).
 */
export function getSacredSitesByCity(cityName: string): SacredSite[] {
  const norm = (cityName || '').trim().toLowerCase();
  if (!norm || norm === 'all india') return getAllSacredSites();
  return getAllSacredSites().filter((site) => site.city.toLowerCase().includes(norm));
}

/**
 * Convert all sacred shrines into the standard MapPointItem format for InteractiveMap.
 */
export function getSacredMapPoints(): Array<{
  id: string;
  name: string;
  type: 'sacred_site';
  lat: number;
  lng: number;
  city: string;
  state: string;
  raw: SacredSite;
}> {
  return getAllSacredSites().map((site) => ({
    id: site.id,
    name: site.name,
    type: 'sacred_site' as const,
    lat: site.coordinates.lat,
    lng: site.coordinates.lng,
    city: site.city,
    state: site.state,
    raw: site,
  }));
}
